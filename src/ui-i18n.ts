export type MessageKey = keyof typeof english;
export type Locale = 'zh-CN' | 'en';
export type LanguagePreference = 'system' | Locale;
export interface NativeLanguage { preference: LanguagePreference; locale: Locale }
export const languageStorageKey = 'nootify-language';
export const isPreference = (value: unknown): value is LanguagePreference => value === 'system' || value === 'zh-CN' || value === 'en';
export function resolveLocale(preference: LanguagePreference, languages: readonly string[]): Locale {
  if (preference !== 'system') return preference;
  for (const language of languages) {
    if (/^zh(?:-|_|$)/i.test(language)) return 'zh-CN';
    if (/^en(?:-|_|$)/i.test(language)) return 'en';
  }
  return 'en';
}
export function translate(locale: Locale, key: MessageKey, values: Record<string, unknown> = {}): string {
  const message: string = locale === 'en' ? english[key] : key;
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => Object.hasOwn(values, name) ? String(values[name] ?? '') : placeholder);
}

let preference: LanguagePreference = 'system';
let nativeLocale: Locale | undefined;
// Importing the pure helpers in Node tests never needs browser globals.
if (typeof window !== 'undefined') {
  const native = (window as Window & { __NOOTIFY_LANGUAGE__?: NativeLanguage }).__NOOTIFY_LANGUAGE__;
  if (native && isPreference(native.preference) && (native.locale === 'en' || native.locale === 'zh-CN')) {
    preference = native.preference; nativeLocale = native.locale;
  } else {
    try { const saved = localStorage.getItem(languageStorageKey); if (isPreference(saved)) preference = saved; } catch { /* Storage is optional. */ }
  }
}
export const languagePreference = (): LanguagePreference => preference;
export const locale = (): Locale => nativeLocale ?? resolveLocale(preference, typeof navigator === 'undefined' ? [] : navigator.languages?.length ? navigator.languages : [navigator.language]);
export const t = (key: MessageKey, values?: Record<string, unknown>): string => translate(locale(), key, values);
export const number = (value: number): string => new Intl.NumberFormat(locale()).format(value);
export const list = (values: string[]): string => new Intl.ListFormat(locale(), { style: 'long', type: 'conjunction' }).format(values);
export function setLanguage(value: LanguagePreference, native?: NativeLanguage): void {
  preference = value;
  nativeLocale = native?.locale;
  try { localStorage.setItem(languageStorageKey, value); } catch { /* Keep the in-memory preference when storage is unavailable. */ }
}
/** Only explicitly marked, trusted catalog strings are translated; user content is never touched. */
export function translateDocument(root: ParentNode = document): void {
  document.documentElement.lang = locale();
  for (const attribute of ['text', 'title', 'aria-label', 'placeholder', 'alt'] as const) {
    const marker = attribute === 'text' ? 'data-i18n' : `data-i18n-${attribute}`;
    for (const element of root.querySelectorAll<HTMLElement>(`[${marker}]`)) {
      const key = element.getAttribute(marker)!;
      if (!Object.hasOwn(english, key)) continue;
      if (attribute === 'text') element.textContent = t(key as MessageKey);
      else element.setAttribute(attribute, t(key as MessageKey));
    }
  }
}
